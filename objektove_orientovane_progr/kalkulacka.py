# vytvoreni Kalkulacky pomoci OOP
class Kalkulacka:
    def scitani(self, cislo1, cislo2):
        return cislo1 + cislo2
    def odcitani(self, cislo1, cislo2):
        return cislo1 - cislo2
    def nasobeni(self, cislo1, cislo2):
        return cislo1 * cislo2
    def deleni(self, cislo1, cislo2):
        return cislo1 / cislo2